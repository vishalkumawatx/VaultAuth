package com.example.authanticator.backup

import androidx.compose.foundation.layout.*
import androidx.compose.foundation.text.KeyboardOptions
import androidx.compose.foundation.text.selection.SelectionContainer
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.outlined.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.input.KeyboardType
import androidx.compose.ui.text.input.PasswordVisualTransformation
import androidx.compose.ui.unit.dp
import androidx.lifecycle.compose.collectAsStateWithLifecycle
import com.example.authanticator.ui.Page
import com.example.authanticator.ui.PageHeader
import com.example.authanticator.ui.VaultViewModel

@Composable
fun BackupScreen(model: VaultViewModel, authenticate: () -> Unit, chooseExport: () -> Unit, chooseImport: () -> Unit, back: () -> Unit) {
    var password by remember { mutableStateOf("") }
    var confirm by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf<String?>(null) }
    var recoveryRecorded by remember { mutableStateOf(false) }
    val authenticated by model.sensitiveReady.collectAsStateWithLifecycle()
    val selected by model.restoreSelected.collectAsStateWithLifecycle()
    val summary by model.restoreSummary.collectAsStateWithLifecycle()
    val busy by model.busy.collectAsStateWithLifecycle()
    Page {
        PageHeader("Backup & restore", back)
        Text("Encrypted backup", style = MaterialTheme.typography.titleLarge)
        Text("Backups contain every setup key. Use a unique passphrase of at least 16 characters, preferably six or more random words, or generate a recovery key. Keep it separately from the backup file.")
        Text("Neither Vault Auth nor the service can recover a lost backup password. Android's automatic backups do not include this vault.")
        OutlinedTextField(password, { password = it.take(256); recoveryRecorded = false }, Modifier.fillMaxWidth(), label = { Text("Passphrase or recovery key") },
            visualTransformation = PasswordVisualTransformation(), keyboardOptions = KeyboardOptions(autoCorrectEnabled = false, keyboardType = KeyboardType.Password), singleLine = true)
        OutlinedButton(onClick = { model.generateRecoveryKey { generated = it; password = it; confirm = ""; recoveryRecorded = false } }, enabled = !busy) {
            Icon(Icons.Outlined.Key, null); Spacer(Modifier.width(8.dp)); Text("Generate recovery key")
        }
        OutlinedTextField(confirm, { confirm = it.take(256) }, Modifier.fillMaxWidth(), label = { Text("Confirm password for export") },
            visualTransformation = PasswordVisualTransformation(), keyboardOptions = KeyboardOptions(autoCorrectEnabled = false, keyboardType = KeyboardType.Password), singleLine = true)
        Row {
            Checkbox(recoveryRecorded, { recoveryRecorded = it })
            Text("I have stored the passphrase or recovery key separately.", Modifier.padding(top = 12.dp).weight(1f))
        }
        OutlinedButton(onClick = authenticate, enabled = !busy, modifier = Modifier.fillMaxWidth()) {
            Icon(Icons.Outlined.Fingerprint, null); Spacer(Modifier.width(8.dp))
            Text(if (authenticated) "Authenticate again" else "Authenticate for backup")
        }
        if (authenticated) Text("Authentication is valid for one operation within 30 seconds.", style = MaterialTheme.typography.bodySmall)
        Button(enabled = !busy && authenticated && password.length >= 16 && password == confirm && recoveryRecorded,
            onClick = { model.createBackup(password.toCharArray(), chooseExport); password = ""; confirm = "" }, modifier = Modifier.fillMaxWidth()) {
            Icon(Icons.Outlined.FileUpload, null); Spacer(Modifier.width(8.dp)); Text("Export encrypted vault")
        }
        HorizontalDivider(Modifier.padding(vertical = 8.dp))
        Text("Restore", style = MaterialTheme.typography.titleLarge)
        Text("Only Vault Auth v1 encrypted .vaultauth files are supported. Select a file, unlock again if prompted, then enter its original passphrase above. Other authenticator exports are not supported.")
        OutlinedButton(onClick = chooseImport, enabled = !busy, modifier = Modifier.fillMaxWidth()) {
            Icon(Icons.Outlined.FolderOpen, null); Spacer(Modifier.width(8.dp)); Text(if (selected) "Choose another backup" else "Choose encrypted backup")
        }
        Button(onClick = { model.previewRestore(password.toCharArray()); password = ""; confirm = "" }, enabled = !busy && selected && authenticated && password.length >= 16,
            modifier = Modifier.fillMaxWidth()) { Text("Verify & review restore") }
    }
    generated?.let { key ->
        AlertDialog(onDismissRequest = { generated = null }, title = { Text("Record your recovery key") },
            text = { Column(verticalArrangement = Arrangement.spacedBy(16.dp)) {
                Text("Write this exact key down and keep it separately. You will need it to decrypt this export on another device. It is not stored by Vault Auth.")
                SelectionContainer { Text(key.chunked(13).joinToString("\n"), fontFamily = FontFamily.Monospace) }
                Text("Enter the key without line breaks in the confirmation field.")
            } }, confirmButton = { TextButton(onClick = { generated = null }) { Text("Continue") } })
    }
    summary?.let {
        AlertDialog(onDismissRequest = model::cancelRestore, title = { Text("Restore verified backup?") }, text = { Text(it) },
            confirmButton = { TextButton(onClick = model::confirmRestore, enabled = !busy) { Text("Restore accounts") } },
            dismissButton = { TextButton(onClick = model::cancelRestore) { Text("Cancel") } })
    }
}